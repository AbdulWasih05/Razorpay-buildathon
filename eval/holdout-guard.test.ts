import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { globSync } from 'node:fs';
import { describe, expect, it } from 'vitest';

import { DEV_CONFIG, generateCorpus } from '@praman/simulator';

import {
  HoldoutAccessError,
  assertDevOnly,
  heldOutIds,
  isHeldOut,
  loadHoldoutManifest,
} from './holdout-guard.js';

/**
 * TASKS.md P1.3 acceptance: "a test proves the dev pipeline cannot read
 * held-out disputes."
 *
 * These tests are the proof. They are deliberately structural -- they check
 * what the code *can* do, not what it happens to do today.
 */

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));

describe('the held-out manifest', () => {
  const manifest = loadHoldoutManifest();

  it('exists, is well formed, and is not empty', () => {
    expect(manifest.corpus).toBe('ood_holdout');
    expect(manifest.size).toBeGreaterThan(0);
    expect(manifest.disputeExternalIds).toHaveLength(manifest.size);
  });

  it('was generated by a different model than the dev corpus uses', () => {
    // The structural basis of the OOD claim: a different lab's model wrote the
    // conversation language. Dev uses committed templates.
    expect(manifest.languageSource).toBe('llm');
    expect(manifest.languageModel).not.toMatch(/claude/i);
    expect(DEV_CONFIG.languageSource).toBe('template');
  });

  it('leaks ids and aggregate counts only -- never case content or per-case labels', () => {
    // If the manifest carried the cases themselves, reading it during
    // development would be exactly the peeking it exists to prevent.
    const raw = readFileSync(fileURLToPath(new URL('./holdout.json', import.meta.url)), 'utf8');
    expect(raw).not.toMatch(/groundTruthRationale/);
    expect(raw).not.toMatch(/conversationTrace/);
    expect(raw).not.toMatch(/"content"/);
    expect(raw).not.toMatch(/"turns"/);
  });
});

describe('assertDevOnly is a real barrier', () => {
  const manifest = loadHoldoutManifest();
  const aHeldOutId = manifest.disputeExternalIds[0] as string;

  it('throws when a held-out dispute id reaches a dev code path', () => {
    expect(() => assertDevOnly([aHeldOutId])).toThrow(HoldoutAccessError);
  });

  it('throws even when the held-out id is buried in a batch of dev ids', () => {
    const devIds = generateCorpus(DEV_CONFIG, 10).disputes.map((d) => d.externalId);
    expect(() => assertDevOnly(devIds)).not.toThrow();
    expect(() => assertDevOnly([...devIds, aHeldOutId])).toThrow(HoldoutAccessError);
  });

  it('names the offending ids, so the failure is diagnosable', () => {
    try {
      assertDevOnly([aHeldOutId]);
      expect.unreachable('should have thrown');
    } catch (error) {
      expect(error).toBeInstanceOf(HoldoutAccessError);
      expect((error as HoldoutAccessError).offendingIds).toEqual([aHeldOutId]);
    }
  });

  it('also guards evidence-pack ids and Razorpay dispute ids', () => {
    expect(isHeldOut(manifest.evidencePackExternalIds[0] as string)).toBe(true);
    expect(isHeldOut(manifest.razorpayDisputeIds[0] as string)).toBe(true);
  });
});

describe('the dev corpus and the held-out corpus are disjoint', () => {
  it('shares not one id, even at a corpus size far larger than we use', () => {
    const dev = generateCorpus(DEV_CONFIG, 200);
    const held = heldOutIds();
    for (const dispute of dev.disputes) {
      expect(held.has(dispute.externalId), `dev id ${dispute.externalId} collides`).toBe(false);
      expect(held.has(dispute.disputeId), `dev dispute id ${dispute.disputeId} collides`).toBe(false);
      expect(held.has(dispute.transaction.pack.externalId)).toBe(false);
    }
  });
});

describe('no dev code path can reach the held-out config', () => {
  /**
   * The strongest guard here: a static check over the source tree. Everything
   * else tests behaviour at runtime; this tests that the *capability* does not
   * exist outside a tiny, deliberate allowlist.
   */
  const ALLOWED = [
    // Defines it.
    'packages/simulator/src/configs.ts',
    // Barrel export.
    'packages/simulator/src/index.ts',
    // Compares the two configs to assert they differ; never generates from it.
    'packages/simulator/src/corpus.test.ts',
    // The deliberate, separate holdout command.
    'scripts/generate-holdout.ts',
    // This guard itself: it names OOD_CONFIG in the pattern it searches for.
    // It imports DEV_CONFIG only and never generates from the holdout config.
    'eval/holdout-guard.test.ts',
    // The eval harness. This is the one thing licensed to score the holdout,
    // and the licence is the whole reason the allowlist exists rather than a
    // blanket ban: "never read during feature development" is a claim about
    // development, and a held-out set that is never scored measures nothing.
    // The harness reads it once, at eval time, and cannot regenerate it --
    // `allowLive` is hard-coded false where the held-out language is replayed.
    'eval/harness.ts',
  ];

  function sourceFiles(): string[] {
    return globSync(['packages/**/src/**/*.ts', 'apps/**/src/**/*.ts', 'scripts/**/*.ts', 'eval/**/*.ts'], {
      cwd: REPO_ROOT,
    })
      .map((p) => p.replace(/\\/g, '/'))
      .filter((p) => !p.includes('node_modules/') && !p.includes('dist/'));
  }

  /**
   * Strip comments before checking. A file that merely *mentions* OOD_CONFIG in
   * a docblock -- as this guard's own source does, and as the seed script does
   * when explaining why it deliberately avoids it -- has no capability to reach
   * the holdout. Only executable code counts.
   */
  function code(relative: string): string {
    const source = readFileSync(new URL(`../${relative}`, import.meta.url), 'utf8');
    return source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
  }

  it('finds the source tree (guard is not silently vacuous)', () => {
    // A glob that matched nothing would make every assertion below pass while
    // checking nothing at all.
    expect(sourceFiles().length).toBeGreaterThan(10);
  });

  it('strips comments correctly (the guard checks code, not prose)', () => {
    // The comment-stripper is load-bearing for the two tests below, so it gets
    // its own assertion rather than being trusted silently.
    expect(code('scripts/seed.ts')).not.toMatch(/does not import/);
    expect(code('scripts/seed.ts')).toMatch(/DEV_CONFIG/);
  });

  it('references OOD_CONFIG in executable code in the allowlisted files only', () => {
    const offenders = sourceFiles().filter(
      (relative) => !ALLOWED.includes(relative) && /\bOOD_CONFIG\b/.test(code(relative)),
    );
    expect(offenders).toEqual([]);
  });

  it('reads holdout.json in eval/ only', () => {
    const offenders = sourceFiles().filter(
      (relative) =>
        !relative.startsWith('eval/') &&
        relative !== 'scripts/generate-holdout.ts' &&
        code(relative).includes('holdout.json'),
    );
    expect(offenders).toEqual([]);
  });

  it('keeps the dev seed script free of any holdout capability', () => {
    expect(/\bOOD_CONFIG\b/.test(code('scripts/seed.ts'))).toBe(false);
    // And it refuses anything but the dev config outright.
    expect(code('scripts/seed.ts')).toMatch(/configName !== 'dev'/);
  });
});
